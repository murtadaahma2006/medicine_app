    switch (specialty.toLowerCase()) {
      case 'obgyn':
      case 'obstetrics':
      case 'gynecology':
      case 'gynecologic_oncology':
      case 'reproductive_endocrinology':
      case 'maternal_fetal_medicine':
        return obgynPrompt;
      case 'surgery':
      case 'general_surgery':
      case 'orthopedics':
      case 'neurosurgery':
      case 'urology':
      case 'plastic_surgery':
      case 'pediatric_surgery':
      case 'surgical_oncology':
      case 'trauma':
        return surgeryPrompt;
      case 'internal_medicine':
      case 'cardiology':
      case 'pulmonology':
      case 'nephrology':
      case 'gastroenterology':
      case 'endocrinology':
      case 'hematology':
      case 'infectious':
      case 'rheumatology':
      case 'neurology':
      case 'oncology':
      default:
        return internalMedicinePrompt;
    }
